import Foundation
func check(_ value:Bool,_ message:String){if !value{fatalError(message)}}
var state=LiveState()
check(state.apply(["type":"snapshot","revision":1,"conversationState":["threadRuntimeStatus":["type":"active","activeFlags":[String]()],"requests":[]]]),"snapshot")
check(state.waiting==nil,"working is not waiting")
check(state.apply(["type":"patches","baseRevision":1,"revision":2,"patches":[["op":"add","path":["threadRuntimeStatus","activeFlags",0],"value":"waitingOnApproval"]]]),"approval patch")
check(state.waiting=="approval","approval detection")
check(state.apply(["type":"patches","baseRevision":2,"revision":3,"patches":[["op":"replace","path":["threadRuntimeStatus","activeFlags",0],"value":"waitingOnUserInput"]]]),"answer patch")
check(state.waiting=="answer","answer detection")
check(state.apply(["type":"patches","baseRevision":3,"revision":4,"patches":[["op":"remove","path":["threadRuntimeStatus","activeFlags",0]]]]),"resume patch")
check(state.waiting==nil,"resume clears wait")
check(!state.apply(["type":"patches","baseRevision":1,"revision":5,"patches":[]]),"revision gap rejected")
check(state.apply(["type":"snapshot","revision":9,"conversationState":["threadRuntimeStatus":["type":"idle","activeFlags":["waitingOnApproval"]]]]),"resnapshot")
check(state.waiting==nil,"idle cannot retain wait")
print("PASS: approval, answer, resume, stale revision rejection, fresh snapshot, idle precedence")
check(state.apply(["type":"snapshot","revision":10,"conversationState":["threadRuntimeStatus":["type":"idle"],"hasUnreadTurn":true]]),"unread snapshot")
check(state.unread==true,"completed unread remains visible")
check(state.apply(["type":"patches","baseRevision":10,"revision":11,"patches":[["op":"replace","path":["hasUnreadTurn"],"value":false]]]),"read patch")
check(state.unread==false,"reading in Codex clears unread")
print("PASS: unread snapshot and Codex read receipt")
var stream=LiveState()
check(stream.apply(["type":"snapshot","revision":1,"conversationState":["turnHistory":["history":["entitiesByKey":["turn:a":["turnId":"a","status":"completed","turnStartedAtMs":1.0]]]]]]),"canonical snapshot")
check(stream.apply(["type":"patches","baseRevision":1,"revision":2,"patches":[["op":"add","path":["turnHistory","history","entitiesByKey","turn:b"],"value":["turnId":"b","status":"completed","turnStartedAtMs":2.0]]]]),"short turn added already complete")
check(stream.latestTurn?.id=="b" && stream.latestTurn?.status=="completed","short completion captured without running poll")
var ledger=NotificationLedger()
let key=NotificationLedger.key(thread:"thread",turn:"b",kind:"completed")
check(ledger.claim(key),"first completion delivered")
check(!ledger.claim(key),"polling completion cannot duplicate live completion")
var restarted=NotificationLedger(sent:ledger.sent)
check(!restarted.claim(key),"restart dedup")
check(restarted.claim(NotificationLedger.key(thread:"thread",turn:"b",kind:"approval",requests:["new-request"])),"new request delivered")
check(NotificationLedger.key(thread:"t",turn:"v",kind:"answer",requests:["b","a"]) == NotificationLedger.key(thread:"t",turn:"v",kind:"answer",requests:["a","b"]),"request order stable")
print("PASS: short live turns, polling/live dedup, restart dedup, independent requests")
var current=CurrentConversationPolicy()
check(current.observe(id:"old-chat",turn:"a",startedAt:100)=="old-chat","initial current")
check(current.observe(id:"new-test-chat",turn:"b",startedAt:110)=="new-test-chat","new Codex conversation follows automatically")
check(current.observe(id:"old-chat",turn:"a",startedAt:100)==nil,"old background completion cannot steal pin")
check(current.observe(id:"new-test-chat",turn:"b",startedAt:110)==nil,"completion of same turn keeps current")
check(current.observe(id:"old-chat",turn:"c",startedAt:120)=="old-chat","new message in existing chat follows")
var restored=CurrentConversationPolicy(started:current.started,turnID:current.turnID)
check(restored.observe(id:"new-test-chat",turn:"b",startedAt:110)==nil,"restart ignores old snapshots")
print("PASS: auto-current follows new chats and messages, preserves completed chat, ignores old completion and reconnect")
var working=WorkingConversations.adding("chat-a",to:[])
working=WorkingConversations.adding("chat-b",to:working)
check(working==["chat-b","chat-a"],"parallel conversations both remain pinned")
working=WorkingConversations.adding("chat-a",to:working)
check(working==["chat-a","chat-b"],"new message reorders without duplicating")
let saved=try! JSONEncoder().encode(working)
check(try! JSONDecoder().decode([String].self,from:saved)==working,"multiple conversations survive restart persistence")
working=WorkingConversations.removing("chat-a",from:working)
check(working==["chat-b"],"removing one does not remove others")
print("PASS: parallel conversation retention, deduplication, persistence and individual removal")
